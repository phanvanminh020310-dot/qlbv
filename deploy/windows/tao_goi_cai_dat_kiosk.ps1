[CmdletBinding()]
param(
    [Parameter(Mandatory = $true)] [string]$Server,
    [Parameter(Mandatory = $true)] [string]$Room,
    [Parameter(Mandatory = $true)] [string]$Certificate,
    [string]$Output
)

# Run this only on an IT-controlled PC after the public server certificate was
# copied by a verified channel. It packages no private key and never contacts
# the network for a certificate.
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $MyInvocation.MyCommand.Path

function Fail([string]$message) { throw $message }
function Get-PublicCertificate([string]$path) {
    $raw = [IO.File]::ReadAllBytes($path)
    $text = [Text.Encoding]::ASCII.GetString($raw)
    if ($text.Contains('-----BEGIN CERTIFICATE-----')) {
        $body = [Text.RegularExpressions.Regex]::Replace($text, '-----BEGIN CERTIFICATE-----|-----END CERTIFICATE-----|\s', '')
        $raw = [Convert]::FromBase64String($body)
    }
    return New-Object Security.Cryptography.X509Certificates.X509Certificate2 -ArgumentList (, $raw)
}

try {
    $uri = $null
    if (-not [Uri]::TryCreate($Server.Trim(), [UriKind]::Absolute, [ref]$uri) -or $uri.Scheme -ne 'https' -or $uri.UserInfo.Length -ne 0 -or $uri.Query.Length -ne 0 -or $uri.Fragment.Length -ne 0 -or $uri.AbsolutePath -ne '/') {
        Fail 'Server phai la HTTPS origin, vi du https://172.16.13.75:3000.'
    }
    $room = $Room.Trim().ToUpperInvariant()
    if ($room -notmatch '^[A-Z0-9][A-Z0-9._-]{0,63}$') { Fail 'Room khong hop le.' }
    $certificatePath = (Resolve-Path -LiteralPath $Certificate -ErrorAction Stop).ProviderPath
    $certificateData = Get-PublicCertificate $certificatePath
    if ($certificateData.HasPrivateKey) { Fail 'Chi dung public certificate .crt/.cer; tuyet doi khong dung private key/PFX.' }
    $now = [DateTime]::Now
    if ($certificateData.NotBefore -gt $now -or $certificateData.NotAfter -le $now) { Fail "Chung chi chua co hieu luc hoac da het han ($($certificateData.NotAfter.ToString('yyyy-MM-dd')))." }
    $san = $certificateData.Extensions | Where-Object { $_.Oid.Value -eq '2.5.29.17' } | Select-Object -First 1
    if ($null -eq $san -or $san.Format($false).IndexOf($uri.Host, [StringComparison]::OrdinalIgnoreCase) -lt 0) { Fail "Chung chi khong co SAN khop $($uri.Host)." }

    $required = @('QLBS_Kiosk.exe', 'cai_dat_kiosk.bat', 'cai_dat_kiosk.ps1')
    foreach ($name in $required) { if (-not (Test-Path -LiteralPath (Join-Path $root $name) -PathType Leaf)) { Fail "Thieu $name. Hay chay script trong thu muc goi phat hanh QLBS Kiosk." } }

    if ([String]::IsNullOrWhiteSpace($Output)) { $Output = Join-Path (Split-Path -Parent $root) ("QLBS_Kiosk_{0}_MotLan" -f $room) }
    $outputPath = [IO.Path]::GetFullPath($Output)
    if (Test-Path -LiteralPath $outputPath) { Fail "Thu muc dich da ton tai: $outputPath" }
    $parent = Split-Path -Parent $outputPath
    if (-not (Test-Path -LiteralPath $parent)) { New-Item -ItemType Directory -Path $parent -Force | Out-Null }
    $stage = Join-Path $parent ('.QLBS_Kiosk_stage_' + [Guid]::NewGuid().ToString('N'))
    New-Item -ItemType Directory -Path $stage -Force | Out-Null
    try {
        foreach ($name in $required) { Copy-Item -LiteralPath (Join-Path $root $name) -Destination (Join-Path $stage $name) }
        $certificateName = 'QLBS_Server_Trust.cer'
        Copy-Item -LiteralPath $certificatePath -Destination (Join-Path $stage $certificateName)
        $certificateHash = (Get-FileHash -LiteralPath (Join-Path $stage $certificateName) -Algorithm SHA256).Hash.ToUpperInvariant()
        @(
            '# QLBS Kiosk site package - generated by hospital IT',
            ('server_url={0}' -f $uri.GetLeftPart([UriPartial]::Authority)),
            ('room_code={0}' -f $room),
            ('certificate_file={0}' -f $certificateName),
            ('certificate_sha256={0}' -f $certificateHash)
        ) | Set-Content -LiteralPath (Join-Path $stage 'QLBS_Kiosk_Install.ini') -Encoding UTF8
        @(
            'QLBS Kiosk site-specific installer',
            ('Server: {0}' -f $uri.GetLeftPart([UriPartial]::Authority)),
            ('Room: {0}' -f $room),
            ('Certificate SHA-256: {0}' -f $certificateHash),
            ('Certificate subject: {0}' -f $certificateData.Subject),
            ('Certificate expires: {0}' -f $certificateData.NotAfter.ToString('yyyy-MM-dd HH:mm:ss')),
            'This package contains only the public certificate. It does not contain a private key.',
            'Run cai_dat_kiosk.bat as Administrator on the workstation. Do not alter the included certificate or INI.'
        ) | Set-Content -LiteralPath (Join-Path $stage 'BUNDLE_INFO.txt') -Encoding UTF8
        Get-ChildItem -LiteralPath $stage -File | Sort-Object Name | ForEach-Object {
            '{0}  {1}' -f (Get-FileHash -LiteralPath $_.FullName -Algorithm SHA256).Hash.ToLowerInvariant(), $_.Name
        } | Set-Content -LiteralPath (Join-Path $stage 'SHA256SUMS.txt') -Encoding ASCII
        Move-Item -LiteralPath $stage -Destination $outputPath
        $zipPath = $outputPath + '.zip'
        Compress-Archive -Path (Join-Path $outputPath '*') -DestinationPath $zipPath -Force
        Write-Host '[OK] Da tao goi cai dat mot lan:' -ForegroundColor Green
        Write-Host "     $zipPath"
        Write-Host "     Server $($uri.GetLeftPart([UriPartial]::Authority)) / phong $room"
        Write-Host 'Chuyen ZIP qua kenh CNTT tin cay; may tram chi can giai nen va chay cai_dat_kiosk.bat.'
    } catch {
        Remove-Item -LiteralPath $stage -Recurse -Force -ErrorAction SilentlyContinue
        throw
    }
} catch {
    Write-Host "[LOI] $($_.Exception.Message)" -ForegroundColor Red
    exit 1
}
